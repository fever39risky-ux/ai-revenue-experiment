// Owner queue with deadline-based priority (owner request 2026-10-12).
// An owner task (requires:["human"] or id owner-*) inherits the sales opportunities of every task it blocks
// (task.opportunities[] on the blocked task, or on the owner task itself):
//   { url, title, budget_jpy, apply_by (ISO), lost_if_missed }
// Priority from the earliest still-open apply_by: <=24h URGENT, <=48h HIGH, else NORMAL (no deadline = NORMAL).
// URGENT/HIGH items are rendered at the top of OWNER_ACTION_REQUIRED.md (scripts/oct/owner_queue.mjs render)
// and escalated as a GitHub issue by .github/workflows/owner-queue.yml — never a "normal wait".

export const URGENT_H = 24, HIGH_H = 48;
export const BEGIN = '<!-- OWNER_QUEUE:BEGIN (generated by scripts/oct/owner_queue.mjs — do not edit by hand) -->';
export const END = '<!-- OWNER_QUEUE:END -->';

const isOwnerTask = t => t && !t.invalid && t.status !== 'done' && ((t.requires || []).includes('human') || String(t.id).startsWith('owner-'));
const blockers = t => [].concat(t.blocked_by || []);

export function priorityFor(hoursLeft) {
  if (hoursLeft == null) return 'NORMAL';
  return hoursLeft <= URGENT_H ? 'URGENT' : hoursLeft <= HIGH_H ? 'HIGH' : 'NORMAL';
}

export function ownerQueue(tasks, nowMs = Date.now()) {
  const open = tasks.filter(t => t && !t.invalid && t.status !== 'done');
  const rank = { URGENT: 0, HIGH: 1, NORMAL: 2 };
  return open.filter(isOwnerTask).map(o => {
    const blocked = open.filter(t => t.id !== o.id && blockers(t).includes(o.id));
    const opps = [...(o.opportunities || []).map(x => ({ ...x, via: o.id })),
      ...blocked.flatMap(t => (t.opportunities || []).map(x => ({ ...x, via: t.id })))]
      .map(x => ({ ...x, hours_left: x.apply_by && !isNaN(Date.parse(x.apply_by)) ? +((Date.parse(x.apply_by) - nowMs) / 3600e3).toFixed(1) : null }));
    const live = opps.filter(x => x.hours_left == null || x.hours_left > 0);
    const lapsed = opps.filter(x => x.hours_left != null && x.hours_left <= 0);
    const hrs = live.map(x => x.hours_left).filter(h => h != null);
    const earliest = hrs.length ? Math.min(...hrs) : null;
    return { id: o.id, title: o.title, site: o.site || o.profile || null, priority: priorityFor(earliest), hours_left: earliest,
      blocks: blocked.map(t => t.id), opportunities: live.sort((a, b) => (a.hours_left ?? 1e9) - (b.hours_left ?? 1e9)), lapsed };
  }).sort((a, b) => rank[a.priority] - rank[b.priority] || (a.hours_left ?? 1e9) - (b.hours_left ?? 1e9));
}

const jst = iso => new Date(Date.parse(iso) + 9 * 3600e3).toISOString().slice(5, 16).replace('-', '/').replace('T', ' ') + ' JST';

export function renderBlock(queue, nowMs = Date.now()) {
  const L = [BEGIN, `_自動生成: ${jst(new Date(nowMs).toISOString())}（URGENT=応募期限24時間以内 / HIGH=48時間以内 / NORMAL=それ以外）_`, ''];
  if (!queue.length) {
    L.push('### 現在、オーナーが行うべき操作はありません', '', '販売動作（CrowdWorks・ココナラの提案送信）は AI が PG-2／PG-1 の範囲で自動実行しています。');
  }
  for (const q of queue) {
    const icon = q.priority === 'URGENT' ? '🚨' : q.priority === 'HIGH' ? '⚠️' : '•';
    L.push(`### ${icon} ${q.priority}${q.hours_left != null ? `（締切まで残り約${Math.max(0, Math.floor(q.hours_left))}時間）` : ''}：${q.title}`, '');
    L.push(`- task \`${q.id}\`${q.site ? ` / サイト: ${q.site}` : ''}${q.blocks.length ? ` / 止まっている作業: ${q.blocks.map(b => '`' + b + '`').join(', ')}` : ''}`);
    if (q.opportunities.length) {
      L.push('- **対象案件（この操作が終わらないと失う可能性のある機会）:**', '', '| 案件 | 予算 | 締切 | 逃した場合に失うもの |', '|---|---|---|---|');
      for (const x of q.opportunities) L.push(`| [${x.title || x.url}](${x.url}) | ${x.budget_jpy != null ? '¥' + Number(x.budget_jpy).toLocaleString('ja-JP') : '-'} | ${x.apply_by ? jst(x.apply_by) : '-'} | ${x.lost_if_missed || '応募機会'} |`);
      L.push('');
    }
    if (q.lapsed.length) L.push(`- 既に締切を過ぎた案件: ${q.lapsed.map(x => x.url).join(', ')}（運用上の失敗として記録対象）`);
    L.push('');
  }
  L.push(END);
  return L.join('\n');
}

export function applyBlock(md, block) {
  if (md.includes(BEGIN.slice(0, 30)) && md.includes(END)) {
    const a = md.indexOf(BEGIN.slice(0, 30)), b = md.indexOf(END) + END.length;
    return md.slice(0, a) + block + md.slice(b);
  }
  const h = '## 現在の依頼（10月）\n';
  const i = md.indexOf(h);
  return i < 0 ? block + '\n\n' + md : md.slice(0, i + h.length) + '\n' + block + '\n' + md.slice(i + h.length);
}
